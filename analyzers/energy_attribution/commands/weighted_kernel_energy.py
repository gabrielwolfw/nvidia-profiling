"""Associate device-level NVML power samples with CUPTI kernel intervals."""

import argparse
from pathlib import Path

from energy_attribution.reporting.weighted_outputs import (
    print_report,
    write_outputs,
)
from energy_attribution.streaming_attribution import (
    WeightedEnergyReport,
    attribute_energy_streaming,
    build_windows,
    empty_attribution,
    integrate_range,
)
from energy_attribution.streaming_io import (
    load_pm_kernel_metrics,
    load_telemetry,
    scan_kernel_metadata,
)


def parse_args():
    parser = argparse.ArgumentParser(
        description="Estimate per-kernel energy from synchronized NVML and "
        "CUPTI timestamps."
    )
    parser.add_argument("--telemetry", required=True, type=Path)
    parser.add_argument("--kernels", required=True, type=Path)
    parser.add_argument(
        "--pm-kernel-metrics",
        type=Path,
        help=(
            "Optional kernel_pm_metrics.csv generated by "
            "analyze_kernel_pm_metrics.py. Enables hybrid PM-weighted "
            "energy attribution."
        ),
    )
    parser.add_argument(
        "--pm-weight-metric",
        default=(
            "sm__inst_executed_realtime.avg." "pct_of_peak_sustained_elapsed"
        ),
        help="PM metric column used as the kernel energy-allocation weight.",
    )
    parser.add_argument(
        "--pm-min-coverage-pct",
        type=float,
        default=99.9,
        help=(
            "Minimum PM coverage required before a kernel can use a PM "
            "weight (default: 99.9)."
        ),
    )
    parser.add_argument(
        "--idle-power-mw",
        type=float,
        default=0.0,
        help=(
            "Optional idle baseline. The default 0 attributes total measured "
            "device energy; a positive value estimates dynamic energy."
        ),
    )
    parser.add_argument("--window-ms", type=float, default=200.0)
    parser.add_argument(
        "--output-dir", type=Path, default=Path("energy-analysis")
    )
    parser.add_argument(
        "--plot",
        action="store_true",
        help="Generate PNG plots (requires matplotlib).",
    )
    return parser.parse_args()


def validate_args(args):
    """Checks numeric options and returns the window length in ns."""
    if args.idle_power_mw < 0:
        raise ValueError("--idle-power-mw cannot be negative")
    if not 0.0 <= args.pm_min_coverage_pct <= 100.0:
        raise ValueError("--pm-min-coverage-pct must be between 0 and 100")
    if args.window_ms <= 0:
        raise ValueError("--window-ms must be greater than zero")
    window_ns = int(args.window_ms * 1_000_000)
    if window_ns < 1:
        raise ValueError("--window-ms must be at least one nanosecond")
    return window_ns


def analysis_range(samples, kernel_metadata, window_ns):
    """Returns the analyzed [start, end) covered by telemetry and kernels."""
    if kernel_metadata["count"]:
        analysis_start = max(samples[0][0], kernel_metadata["first_start"])
        kernel_span_ns = max(0, kernel_metadata["last_end"] - analysis_start)
        full_window_end = (
            analysis_start
            + ((kernel_span_ns + window_ns - 1) // window_ns) * window_ns
        )
        analysis_end = min(samples[-1][0], full_window_end)
        if analysis_end < full_window_end:
            print(
                "WARNING: Telemetry does not cover the complete final window; "
                "capture a new run with additional tail sampling."
            )
    else:
        print(
            "WARNING: No valid kernel intervals were found; "
            "analyzing the complete NVML timeline with 0% kernel activity."
        )
        analysis_start = samples[0][0]
        analysis_end = samples[-1][0]
    if analysis_start >= analysis_end:
        raise ValueError("Telemetry and kernel timelines do not overlap")
    return analysis_start, analysis_end


def analyze(args, window_ns, samples, pm_by_event_id, kernel_metadata):
    """Integrates telemetry energy and attributes it to kernels."""
    start, end = analysis_range(samples, kernel_metadata, window_ns)
    device_energy, dynamic_energy = integrate_range(
        samples, start, end, args.idle_power_mw
    )
    if kernel_metadata["count"]:
        print("Attributing energy with a chronological sweep...", flush=True)
        attribution = attribute_energy_streaming(
            samples,
            args.kernels,
            pm_by_event_id,
            start,
            end,
            args.idle_power_mw,
            window_ns,
        )
    else:
        attribution = empty_attribution(dynamic_energy, start, end, window_ns)
    windows = build_windows(
        samples,
        attribution["window_active_ns"],
        start,
        end,
        args.idle_power_mw,
        window_ns,
    )
    return WeightedEnergyReport(
        analysis_start=start,
        analysis_end=end,
        device_energy=device_energy,
        dynamic_energy=dynamic_energy,
        attribution=attribution,
        windows=windows,
        kernel_metadata=kernel_metadata,
    )


def main():
    args = parse_args()
    window_ns = validate_args(args)
    samples = load_telemetry(args.telemetry)
    pm_by_event_id = {}
    if args.pm_kernel_metrics:
        pm_by_event_id = load_pm_kernel_metrics(
            args.pm_kernel_metrics,
            args.pm_weight_metric,
            args.pm_min_coverage_pct,
        )
    print("Scanning kernel activity metadata...", flush=True)
    kernel_metadata = scan_kernel_metadata(args.kernels, pm_by_event_id)
    kernel_count = kernel_metadata["count"]
    print(f"Validated {kernel_count} kernel events.", flush=True)
    report = analyze(args, window_ns, samples, pm_by_event_id, kernel_metadata)
    write_outputs(args, report, pm_by_event_id)
    print_report(args, report)


if __name__ == "__main__":
    main()
