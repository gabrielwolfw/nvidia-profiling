#!/usr/bin/env python3
"""Plan and execute reproducible GPU power-cycle benchmark studies."""

from __future__ import annotations

import argparse
import csv
import json
import math
import random
import re
import shutil
import subprocess
import sys
from dataclasses import asdict, dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Any


SUPPORTED_WORKLOADS = {"idle", "compute", "memory", "mixed"}
PLAN_FIELDS = (
    "sequence",
    "repetition",
    "condition_id",
    "workload_name",
    "workload_kind",
    "duty_cycle_pct",
    "warmup_seconds",
    "measurement_seconds",
    "cooldown_seconds",
    "period_ms",
    "status",
    "result_directory",
    "return_code",
)
RESULT_PATTERN = re.compile(r'^Results:\s+"?([^"\n]+)"?\s*$', re.MULTILINE)


@dataclass(frozen=True)
class ModeConfig:
    """Timing and repetition settings for one study mode."""

    warmup_seconds: float
    measurement_seconds: float
    cooldown_seconds: float
    repetitions: int
    duty_cycles_pct: tuple[float, ...]


@dataclass(frozen=True)
class WorkloadConfig:
    """One workload family and its optional CUDA parameters."""

    name: str
    kind: str
    duty_cycles_pct: tuple[float, ...] | None
    iterations: int
    buffer_bytes: int
    mixed_compute_pct: int


@dataclass(frozen=True)
class SweepConfig:
    """Validated benchmark study configuration."""

    device: int
    window_ms: int
    period_ms: float
    seed: int
    modes: dict[str, ModeConfig]
    workloads: tuple[WorkloadConfig, ...]


@dataclass
class PlanEntry:  # pylint: disable=too-many-instance-attributes
    """One executable benchmark condition in randomized order."""

    # A flat record intentionally mirrors the durable execution_plan.csv schema.

    sequence: int
    repetition: int
    condition_id: str
    workload_name: str
    workload_kind: str
    duty_cycle_pct: float
    warmup_seconds: float
    measurement_seconds: float
    cooldown_seconds: float
    period_ms: float
    status: str = "pending"
    result_directory: str = ""
    return_code: str = ""


def parse_args() -> argparse.Namespace:
    """Parse command-line options."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", required=True, type=Path)
    parser.add_argument("--mode", choices=("pilot", "production"), required=True)
    parser.add_argument("--launcher", type=Path)
    parser.add_argument("--benchmark", type=Path)
    parser.add_argument("--socket", type=Path)
    parser.add_argument("--library", type=Path)
    parser.add_argument("--output-dir", required=True, type=Path)
    parser.add_argument("--seed", type=int)
    parser.add_argument(
        "--levels-file",
        type=Path,
        help=(
            "Production duty cycles generated by analyze_power_sweep.py. "
            "Every non-idle workload must be present."
        ),
    )
    parser.add_argument(
        "--plan-only",
        action="store_true",
        help="Write and validate the randomized plan without executing it.",
    )
    parser.add_argument(
        "--resume",
        action="store_true",
        help="Resume pending entries from an existing compatible plan.",
    )
    parser.add_argument(
        "--fail-fast",
        action="store_true",
        help="Stop after the first failed session instead of preserving progress.",
    )
    return parser.parse_args()


def require_mapping(value: Any, label: str) -> dict[str, Any]:
    """Return a JSON object or raise a descriptive configuration error."""
    if not isinstance(value, dict):
        raise ValueError(f"{label} must be a JSON object")
    return value


def require_number(value: Any, label: str, *, minimum: float = 0.0) -> float:
    """Validate a finite numeric setting with an inclusive minimum."""
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise ValueError(f"{label} must be numeric")
    parsed = float(value)
    if not math.isfinite(parsed) or parsed < minimum:
        raise ValueError(f"{label} must be finite and at least {minimum}")
    return parsed


def require_integer(value: Any, label: str, *, minimum: int = 0) -> int:
    """Validate an integer setting with an inclusive minimum."""
    if isinstance(value, bool) or not isinstance(value, int) or value < minimum:
        raise ValueError(f"{label} must be an integer of at least {minimum}")
    return value


def parse_duty_cycles(value: Any, label: str) -> tuple[float, ...]:
    """Validate and normalize an ordered set of duty-cycle percentages."""
    if not isinstance(value, list) or not value:
        raise ValueError(f"{label} must be a non-empty JSON array")
    cycles = tuple(require_number(item, label) for item in value)
    if any(item > 100.0 for item in cycles):
        raise ValueError(f"{label} values must be in [0, 100]")
    if len(set(cycles)) != len(cycles):
        raise ValueError(f"{label} cannot contain duplicates")
    return cycles


def parse_mode(name: str, raw_value: Any) -> ModeConfig:
    """Parse one pilot or production mode."""
    raw = require_mapping(raw_value, f"modes.{name}")
    measurement = require_number(
        raw.get("measurement_seconds"),
        f"modes.{name}.measurement_seconds",
        minimum=0.001,
    )
    return ModeConfig(
        warmup_seconds=require_number(
            raw.get("warmup_seconds"), f"modes.{name}.warmup_seconds"
        ),
        measurement_seconds=measurement,
        cooldown_seconds=require_number(
            raw.get("cooldown_seconds"), f"modes.{name}.cooldown_seconds"
        ),
        repetitions=require_integer(
            raw.get("repetitions"), f"modes.{name}.repetitions", minimum=1
        ),
        duty_cycles_pct=parse_duty_cycles(
            raw.get("duty_cycles_pct"), f"modes.{name}.duty_cycles_pct"
        ),
    )


def parse_workload(index: int, raw_value: Any) -> WorkloadConfig:
    """Parse one workload definition."""
    label = f"workloads[{index}]"
    raw = require_mapping(raw_value, label)
    name = raw.get("name")
    kind = raw.get("kind")
    if not isinstance(name, str) or not name or not re.fullmatch(r"[a-z0-9-]+", name):
        raise ValueError(f"{label}.name must contain lowercase letters, digits, or '-'")
    if kind not in SUPPORTED_WORKLOADS:
        raise ValueError(
            f"{label}.kind must be one of {sorted(SUPPORTED_WORKLOADS)}"
        )
    override = raw.get("duty_cycles_pct")
    duty_cycles = None if override is None else parse_duty_cycles(
        override, f"{label}.duty_cycles_pct"
    )
    if kind == "idle" and duty_cycles not in (None, (0.0,)):
        raise ValueError(f"{label}: idle workload only supports duty cycle 0")
    iterations = require_integer(
        raw.get("iterations", 10000), f"{label}.iterations", minimum=1
    )
    buffer_bytes = require_integer(
        raw.get("buffer_bytes", 268435456),
        f"{label}.buffer_bytes",
        minimum=4,
    )
    if buffer_bytes % 4:
        raise ValueError(f"{label}.buffer_bytes must be a multiple of 4")
    mixed_compute_pct = require_integer(
        raw.get("mixed_compute_pct", 50),
        f"{label}.mixed_compute_pct",
    )
    if mixed_compute_pct > 100:
        raise ValueError(f"{label}.mixed_compute_pct must be in [0, 100]")
    return WorkloadConfig(
        name=name,
        kind=kind,
        duty_cycles_pct=duty_cycles,
        iterations=iterations,
        buffer_bytes=buffer_bytes,
        mixed_compute_pct=mixed_compute_pct,
    )


def load_config(path: Path) -> SweepConfig:
    """Load and strictly validate a power-sweep JSON configuration."""
    with path.open(encoding="utf-8") as source:
        raw = require_mapping(json.load(source), "configuration")
    if raw.get("schema_version") != 1:
        raise ValueError("schema_version must be 1")
    modes_raw = require_mapping(raw.get("modes"), "modes")
    missing_modes = {"pilot", "production"} - set(modes_raw)
    if missing_modes:
        raise ValueError(f"modes is missing {sorted(missing_modes)}")
    workloads_raw = raw.get("workloads")
    if not isinstance(workloads_raw, list) or not workloads_raw:
        raise ValueError("workloads must be a non-empty JSON array")
    workloads = tuple(
        parse_workload(index, item) for index, item in enumerate(workloads_raw)
    )
    names = [item.name for item in workloads]
    if len(names) != len(set(names)):
        raise ValueError("workload names must be unique")
    window_ms = require_integer(raw.get("window_ms"), "window_ms", minimum=1)
    period_ms = require_number(raw.get("period_ms"), "period_ms", minimum=0.001)
    if period_ms > window_ms:
        raise ValueError("period_ms cannot exceed window_ms")
    return SweepConfig(
        device=require_integer(raw.get("device"), "device"),
        window_ms=window_ms,
        period_ms=period_ms,
        seed=require_integer(raw.get("seed"), "seed"),
        modes={name: parse_mode(name, value) for name, value in modes_raw.items()},
        workloads=workloads,
    )


def format_number(value: float) -> str:
    """Format numbers reproducibly for command lines and identifiers."""
    return f"{value:.6f}".rstrip("0").rstrip(".")


def build_plan(
    config: SweepConfig,
    mode_name: str,
    seed: int,
    level_overrides: dict[str, tuple[float, ...]] | None = None,
) -> list[PlanEntry]:
    """Build a balanced, block-randomized plan."""
    mode = config.modes[mode_name]
    base_conditions: list[tuple[WorkloadConfig, float]] = []
    for workload in config.workloads:
        duty_cycles = (
            (level_overrides or {}).get(workload.name)
            or workload.duty_cycles_pct
            or mode.duty_cycles_pct
        )
        for duty_cycle in duty_cycles:
            if workload.kind == "idle" and duty_cycle != 0.0:
                continue
            base_conditions.append((workload, duty_cycle))

    randomizer = random.Random(seed)
    plan: list[PlanEntry] = []
    sequence = 1
    for repetition in range(1, mode.repetitions + 1):
        block = list(base_conditions)
        randomizer.shuffle(block)
        for workload, duty_cycle in block:
            duty_label = format_number(duty_cycle).replace(".", "p")
            plan.append(
                PlanEntry(
                    sequence=sequence,
                    repetition=repetition,
                    condition_id=f"{workload.name}-duty-{duty_label}",
                    workload_name=workload.name,
                    workload_kind=workload.kind,
                    duty_cycle_pct=duty_cycle,
                    warmup_seconds=mode.warmup_seconds,
                    measurement_seconds=mode.measurement_seconds,
                    cooldown_seconds=mode.cooldown_seconds,
                    period_ms=config.period_ms,
                )
            )
            sequence += 1
    return plan


def read_level_overrides(path: Path) -> dict[str, list[float]]:
    """Read workload duty cycles from an analyzer-generated CSV."""
    with path.open(newline="", encoding="utf-8") as source:
        reader = csv.DictReader(source)
        required = {"workload_name", "duty_cycle_pct"}
        missing = required - set(reader.fieldnames or [])
        if missing:
            raise ValueError(f"levels file is missing columns: {sorted(missing)}")
        grouped: dict[str, list[float]] = {}
        for row in reader:
            workload_name = row["workload_name"]
            duty_cycle = require_number(
                float(row["duty_cycle_pct"]), "levels duty_cycle_pct"
            )
            if duty_cycle > 100.0:
                raise ValueError("levels duty_cycle_pct must be in [0, 100]")
            grouped.setdefault(workload_name, []).append(duty_cycle)
    return grouped


def load_level_overrides(
    path: Path, config: SweepConfig
) -> dict[str, tuple[float, ...]]:
    """Load and validate pilot-selected levels for a production plan."""
    grouped = read_level_overrides(path)
    configured = {workload.name: workload for workload in config.workloads}
    unknown = set(grouped) - set(configured)
    if unknown:
        raise ValueError(f"levels file contains unknown workloads: {sorted(unknown)}")
    required_workloads = {
        workload.name for workload in config.workloads if workload.kind != "idle"
    }
    missing_workloads = required_workloads - set(grouped)
    if missing_workloads:
        raise ValueError(
            "levels file is missing non-idle workloads: "
            f"{sorted(missing_workloads)}"
        )
    overrides = {}
    for name, values in grouped.items():
        if len(values) != len(set(values)):
            raise ValueError(f"levels file contains duplicate levels for {name}")
        overrides[name] = tuple(values)
    return overrides


def atomic_write_json(path: Path, value: Any) -> None:
    """Atomically replace a JSON file."""
    temporary = path.with_name(path.name + ".tmp")
    with temporary.open("w", encoding="utf-8") as destination:
        json.dump(value, destination, indent=2)
        destination.write("\n")
    temporary.replace(path)


def write_plan(path: Path, plan: list[PlanEntry]) -> None:
    """Atomically write the execution plan and its current statuses."""
    temporary = path.with_name(path.name + ".tmp")
    with temporary.open("w", newline="", encoding="utf-8") as destination:
        writer = csv.DictWriter(destination, fieldnames=PLAN_FIELDS)
        writer.writeheader()
        writer.writerows(asdict(entry) for entry in plan)
    temporary.replace(path)


def load_plan(path: Path) -> list[PlanEntry]:
    """Load an existing plan for safe resumption."""
    with path.open(newline="", encoding="utf-8") as source:
        rows = list(csv.DictReader(source))
    plan = []
    for row in rows:
        plan.append(
            PlanEntry(
                sequence=int(row["sequence"]),
                repetition=int(row["repetition"]),
                condition_id=row["condition_id"],
                workload_name=row["workload_name"],
                workload_kind=row["workload_kind"],
                duty_cycle_pct=float(row["duty_cycle_pct"]),
                warmup_seconds=float(row["warmup_seconds"]),
                measurement_seconds=float(row["measurement_seconds"]),
                cooldown_seconds=float(row["cooldown_seconds"]),
                period_ms=float(row["period_ms"]),
                status=row["status"],
                result_directory=row["result_directory"],
                return_code=row["return_code"],
            )
        )
    return plan


def workload_by_name(config: SweepConfig, name: str) -> WorkloadConfig:
    """Find a validated workload by its stable name."""
    return next(workload for workload in config.workloads if workload.name == name)


def build_command(
    args: argparse.Namespace,
    config: SweepConfig,
    workload: WorkloadConfig,
    entry: PlanEntry,
) -> list[str]:
    """Build a shell-free launcher command for one plan entry."""
    total_seconds = (
        entry.warmup_seconds
        + entry.measurement_seconds
        + entry.cooldown_seconds
    )
    command = [
        str(args.launcher),
        "--device",
        str(config.device),
        "--duration",
        str(math.ceil(total_seconds) + 10),
        "--window-ms",
        str(config.window_ms),
    ]
    if args.socket is not None:
        command.extend(("--socket", str(args.socket)))
    if args.library is not None:
        command.extend(("--library", str(args.library)))
    command.extend(
        (
            "--command",
            "--",
            str(args.benchmark),
            "--device",
            str(config.device),
            "--workload",
            workload.kind,
            "--warmup-seconds",
            format_number(entry.warmup_seconds),
            "--duration",
            format_number(entry.measurement_seconds),
            "--cooldown-seconds",
            format_number(entry.cooldown_seconds),
            "--duty-cycle",
            format_number(entry.duty_cycle_pct),
            "--period-ms",
            format_number(entry.period_ms),
            "--iterations",
            str(workload.iterations),
            "--size",
            str(workload.buffer_bytes),
            "--mixed-compute-pct",
            str(workload.mixed_compute_pct),
        )
    )
    return command


def extract_result_directory(output: str) -> Path | None:
    """Extract the daemon-owned result directory printed by the launcher."""
    matches = RESULT_PATTERN.findall(output)
    return Path(matches[-1].strip()) if matches else None


def next_session_directory(sessions_directory: Path, base_name: str) -> Path:
    """Choose a new attempt directory without deleting earlier evidence."""
    candidate = sessions_directory / base_name
    attempt = 2
    while candidate.exists():
        candidate = sessions_directory / f"{base_name}-attempt-{attempt:02d}"
        attempt += 1
    return candidate


def run_session_command(command: list[str], timeout_seconds: float) -> tuple[int, str]:
    """Run a launcher command and return its status and combined output."""
    try:
        completed = subprocess.run(
            command,
            check=False,
            capture_output=True,
            text=True,
            timeout=timeout_seconds,
        )
        return completed.returncode, completed.stdout + completed.stderr
    except subprocess.TimeoutExpired as error:
        stdout = error.stdout or ""
        stderr = error.stderr or ""
        if isinstance(stdout, bytes):
            stdout = stdout.decode(errors="replace")
        if isinstance(stderr, bytes):
            stderr = stderr.decode(errors="replace")
        return 124, stdout + stderr + "\nERROR: benchmark session timed out\n"


def preserve_session_results(output: str, destination: Path) -> Path | None:
    """Copy daemon results into the durable study directory when available."""
    source_directory = extract_result_directory(output)
    if source_directory is not None and source_directory.is_dir():
        shutil.copytree(source_directory, destination, dirs_exist_ok=True)
    return source_directory


def execute_entry(
    args: argparse.Namespace,
    config: SweepConfig,
    entry: PlanEntry,
    sessions_directory: Path,
) -> None:
    """Execute one plan entry and preserve all available evidence."""
    workload = workload_by_name(config, entry.workload_name)
    command = build_command(args, config, workload, entry)
    session_name = (
        f"{entry.sequence:03d}-{entry.condition_id}-rep-{entry.repetition:02d}"
    )
    destination = next_session_directory(sessions_directory, session_name)
    destination.mkdir(parents=True, exist_ok=False)
    entry.status = "running"

    timeout_seconds = (
        entry.warmup_seconds
        + entry.measurement_seconds
        + entry.cooldown_seconds
        + 180.0
    )
    started_at = datetime.now(timezone.utc).isoformat()
    return_code, output = run_session_command(command, timeout_seconds)

    (destination / "benchmark.log").write_text(output, encoding="utf-8")
    print(output, end="" if output.endswith("\n") else "\n")
    source_directory = preserve_session_results(output, destination)
    entry.result_directory = str(destination)

    entry.return_code = str(return_code)
    entry.status = "completed" if return_code == 0 else "failed"
    condition = {
        **asdict(entry),
        "device": config.device,
        "window_ms": config.window_ms,
        "command": command,
        "source_result_directory": (
            str(source_directory) if source_directory is not None else None
        ),
        "started_at_utc": started_at,
        "finished_at_utc": datetime.now(timezone.utc).isoformat(),
    }
    atomic_write_json(destination / "condition.json", condition)


def prepare_study(
    args: argparse.Namespace,
    config: SweepConfig,
    seed: int,
    level_overrides: dict[str, tuple[float, ...]] | None,
) -> tuple[list[PlanEntry], Path]:
    """Create a new study or safely resume an existing one."""
    plan_path = args.output_dir / "execution_plan.csv"
    if plan_path.exists():
        if not args.resume:
            raise ValueError(
                f"{plan_path} already exists; pass --resume to continue it"
            )
        plan = load_plan(plan_path)
        experiment_path = args.output_dir / "experiment.json"
        with experiment_path.open(encoding="utf-8") as source:
            experiment = require_mapping(json.load(source), "experiment")
        if experiment.get("mode") != args.mode:
            raise ValueError(
                "--mode does not match the existing experiment: "
                f"{experiment.get('mode')}"
            )
        if int(experiment.get("seed", -1)) != seed:
            raise ValueError("seed does not match the existing experiment")
    else:
        if args.resume:
            raise ValueError(f"cannot resume because {plan_path} does not exist")
        if args.output_dir.exists() and any(args.output_dir.iterdir()):
            raise ValueError(
                f"output directory is not empty and has no plan: {args.output_dir}"
            )
        args.output_dir.mkdir(parents=True, exist_ok=True)
        plan = build_plan(config, args.mode, seed, level_overrides)
        write_plan(plan_path, plan)
        atomic_write_json(
            args.output_dir / "experiment.json",
            {
                "schema_version": 1,
                "mode": args.mode,
                "seed": seed,
                "config": str(args.config),
                "created_at_utc": datetime.now(timezone.utc).isoformat(),
                "device": config.device,
                "window_ms": config.window_ms,
                "entries": len(plan),
                "levels_file": (
                    str(args.levels_file) if args.levels_file is not None else None
                ),
            },
        )
    return plan, plan_path


def validate_executables(args: argparse.Namespace) -> None:
    """Reject missing executables before starting a multi-hour study."""
    for label, path in (("launcher", args.launcher), ("benchmark", args.benchmark)):
        if path is None:
            raise ValueError(f"--{label} is required unless --plan-only is used")
        if not path.is_file():
            raise ValueError(f"{label} does not exist: {path}")
        if not path.stat().st_mode & 0o111:
            raise ValueError(f"{label} is not executable: {path}")


def main() -> int:
    """Program entry point."""
    args = parse_args()
    try:
        config = load_config(args.config)
        seed = config.seed if args.seed is None else args.seed
        if args.levels_file is not None and args.mode != "production":
            raise ValueError("--levels-file is only valid in production mode")
        level_overrides = (
            load_level_overrides(args.levels_file, config)
            if args.levels_file is not None
            else None
        )
        plan, plan_path = prepare_study(args, config, seed, level_overrides)
        pending = [entry for entry in plan if entry.status != "completed"]
        print(
            f"Study mode: {args.mode}\n"
            f"Total sessions: {len(plan)}\n"
            f"Pending sessions: {len(pending)}\n"
            f"Plan: {plan_path}"
        )
        if args.plan_only:
            return 0
        validate_executables(args)
        sessions_directory = args.output_dir / "sessions"
        sessions_directory.mkdir(parents=True, exist_ok=True)

        failures = 0
        for entry in pending:
            print(
                f"\n[{entry.sequence}/{len(plan)}] {entry.condition_id} "
                f"repetition {entry.repetition}"
            )
            try:
                execute_entry(args, config, entry, sessions_directory)
            except KeyboardInterrupt:
                entry.status = "interrupted"
                write_plan(plan_path, plan)
                raise
            except (OSError, subprocess.SubprocessError) as error:
                entry.status = "failed"
                entry.return_code = "runner-error"
                failures += 1
                print(f"ERROR: {error}", file=sys.stderr)
            else:
                if entry.status != "completed":
                    failures += 1
            write_plan(plan_path, plan)
            if failures and args.fail_fast:
                break
        return 1 if failures else 0
    except (OSError, ValueError, json.JSONDecodeError) as error:
        print(f"ERROR: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
