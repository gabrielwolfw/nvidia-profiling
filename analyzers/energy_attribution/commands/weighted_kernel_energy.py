"""Associate device-level NVML power samples with CUPTI kernel intervals."""

import argparse
from array import array
import csv
import heapq
import math
from pathlib import Path


NS_PER_SECOND = 1_000_000_000

def parse_args():
    parser = argparse.ArgumentParser(
        description="Estimate per-kernel energy from synchronized NVML and CUPTI timestamps."
    )
    parser.add_argument("--telemetry", required=True, type=Path)
    parser.add_argument("--kernels", required=True, type=Path)
    parser.add_argument(
        "--pm-kernel-metrics",
        type=Path,
        help=(
            "Optional kernel_pm_metrics.csv generated by "
            "analyze_kernel_pm_metrics.py. Enables hybrid PM-weighted "
            "energy attribution."
        ),
    )
    parser.add_argument(
        "--pm-weight-metric",
        default=(
            "sm__inst_executed_realtime.avg."
            "pct_of_peak_sustained_elapsed"
        ),
        help="PM metric column used as the kernel energy-allocation weight.",
    )
    parser.add_argument(
        "--pm-min-coverage-pct",
        type=float,
        default=99.9,
        help=(
            "Minimum PM coverage required before a kernel can use a PM "
            "weight (default: 99.9)."
        ),
    )
    parser.add_argument(
        "--idle-power-mw",
        type=float,
        default=0.0,
        help=(
            "Optional idle baseline. The default 0 attributes total measured "
            "device energy; a positive value estimates dynamic energy."
        ),
    )
    parser.add_argument("--window-ms", type=float, default=200.0)
    parser.add_argument("--output-dir", type=Path, default=Path("energy-analysis"))
    parser.add_argument(
        "--plot",
        action="store_true",
        help="Generate PNG plots (requires matplotlib).",
    )
    return parser.parse_args()


def load_telemetry(path):
    samples = []
    skipped = 0
    with path.open(newline="", encoding="utf-8") as source:
        reader = csv.DictReader(source)
        required_fields = {"timestamp_ns", "power_mw"}
        missing_fields = required_fields - set(reader.fieldnames or [])
        if missing_fields:
            raise ValueError(
                "Telemetry CSV is missing columns: "
                f"{sorted(missing_fields)}"
            )
        for row in reader:
            try:
                samples.append(
                    (int(row["timestamp_ns"]), float(row["power_mw"]))
                )
            except (TypeError, ValueError):
                skipped += 1
    if skipped:
        print(f"WARNING: Skipped {skipped} invalid telemetry rows.")
    samples.sort()
    deduplicated = []
    for timestamp, power in samples:
        if deduplicated and timestamp == deduplicated[-1][0]:
            deduplicated[-1] = (timestamp, power)
        else:
            deduplicated.append((timestamp, power))
    if len(deduplicated) < 2:
        raise ValueError("At least two distinct telemetry timestamps are required")
    return deduplicated


def load_pm_kernel_metrics(path, weight_metric, min_coverage_pct):
    """Load valid PM weights by event ID without loading CSV rows twice.

    The PM file is already an offline timestamp join. A weight is used only
    when a kernel has sufficient PM coverage and a positive finite value for
    the selected PM metric. Event IDs are unique within one CUPTI trace.
    """
    pm_by_event_id = {}
    row_count = 0
    with path.open(newline="", encoding="utf-8") as source:
        reader = csv.DictReader(source)
        required_fields = {"event_id", "pm_coverage_pct", weight_metric}
        missing_fields = required_fields - set(reader.fieldnames or [])
        if missing_fields:
            raise ValueError(
                "PM kernel metrics CSV is missing columns: "
                f"{sorted(missing_fields)}"
            )
        for row in reader:
            row_count += 1
            event_id = row.get("event_id")
            if event_id in pm_by_event_id:
                raise ValueError(f"Duplicate PM metrics event_id: {event_id}")
            try:
                coverage_pct = float(row["pm_coverage_pct"])
                weight = float(row[weight_metric])
            except (TypeError, ValueError):
                continue
            if not math.isfinite(coverage_pct) or not math.isfinite(weight):
                continue
            eligible_weight = (
                weight
                if coverage_pct >= min_coverage_pct and weight > 0.0
                else None
            )
            pm_by_event_id[event_id] = (coverage_pct, eligible_weight)
    if row_count == 0:
        raise ValueError("PM kernel metrics CSV is empty")
    return pm_by_event_id


def parse_kernel_row(row):
    try:
        start = int(row["start_ns"])
        end = int(row["end_ns"])
    except (KeyError, TypeError, ValueError):
        return None
    if end <= start:
        return None
    return start, end


def scan_kernel_metadata(path, pm_by_event_id):
    required_fields = {"event_id", "start_ns", "end_ns"}
    valid_count = 0
    skipped = 0
    first_start = None
    last_end = None
    previous_start = None
    pm_matched = 0
    pm_eligible = 0

    with path.open(newline="", encoding="utf-8") as source:
        reader = csv.DictReader(source)
        missing_fields = required_fields - set(reader.fieldnames or [])
        if missing_fields:
            raise ValueError(
                "Kernel activity CSV is missing columns: "
                f"{sorted(missing_fields)}"
            )
        for row in reader:
            interval = parse_kernel_row(row)
            if interval is None:
                skipped += 1
                continue
            start, end = interval
            if previous_start is not None and start < previous_start:
                raise ValueError(
                    "Kernel activity rows must be sorted by start_ns for "
                    "streaming analysis"
                )
            previous_start = start
            valid_count += 1
            if first_start is None:
                first_start = start
            last_end = end if last_end is None else max(last_end, end)

            pm_values = pm_by_event_id.get(row.get("event_id"))
            if pm_values is not None:
                pm_matched += 1
                if pm_values[1] is not None:
                    pm_eligible += 1

    if skipped:
        print(f"WARNING: Skipped {skipped} invalid kernel rows.")
    return {
        "count": valid_count,
        "first_start": first_start,
        "last_end": last_end,
        "pm_matched": pm_matched,
        "pm_eligible": pm_eligible,
    }


def iter_kernels(path, pm_by_event_id):
    valid_index = 0
    with path.open(newline="", encoding="utf-8") as source:
        reader = csv.DictReader(source)
        for row in reader:
            interval = parse_kernel_row(row)
            if interval is None:
                continue
            start, end = interval
            pm_values = pm_by_event_id.get(row.get("event_id"))
            weight = pm_values[1] if pm_values is not None else None
            yield valid_index, start, end, weight
            valid_index += 1


def interpolated_power(timestamp, left, right, idle_power_mw):
    left_t, left_p = left
    right_t, right_p = right
    fraction = (timestamp - left_t) / (right_t - left_t)
    device_power = left_p + fraction * (right_p - left_p)
    return device_power, max(0.0, device_power - idle_power_mw)


def interval_energy_mj(start, end, left, right, idle_power_mw):
    start_device, start_dynamic = interpolated_power(
        start, left, right, idle_power_mw
    )
    end_device, end_dynamic = interpolated_power(
        end, left, right, idle_power_mw
    )
    duration_seconds = (end - start) / NS_PER_SECOND
    return (
        0.5 * (start_device + end_device) * duration_seconds,
        0.5 * (start_dynamic + end_dynamic) * duration_seconds,
    )


def integrate_range(samples, start, end, idle_power_mw):
    device_energy = 0.0
    dynamic_energy = 0.0
    for left, right in zip(samples, samples[1:]):
        overlap_start = max(start, left[0])
        overlap_end = min(end, right[0])
        if overlap_start >= overlap_end:
            continue
        device, dynamic = interval_energy_mj(
            overlap_start, overlap_end, left, right, idle_power_mw
        )
        device_energy += device
        dynamic_energy += dynamic
    return device_energy, dynamic_energy


def attribute_energy_streaming(
    samples,
    kernel_path,
    pm_by_event_id,
    start,
    end,
    idle_power_mw,
    window_ns,
):
    """Attribute energy with a chronological sweep over kernel boundaries."""
    assigned = 0.0
    unassigned = 0.0
    pm_weighted = 0.0
    fallback = 0.0
    estimated_energy = array("d")
    pm_weighted_energy = array("d")
    fallback_energy = array("d")

    window_count = (end - start + window_ns - 1) // window_ns
    window_active_ns = array("d", [0.0]) * window_count
    window_union_end = array("q", [-1]) * window_count

    kernel_iterator = iter_kernels(kernel_path, pm_by_event_id)

    def read_next_kernel():
        kernel = next(kernel_iterator, None)
        if kernel is None:
            return None
        index, kernel_start, kernel_end, _ = kernel
        if index != len(estimated_energy):
            raise RuntimeError("Kernel stream index is not contiguous")
        estimated_energy.append(0.0)
        pm_weighted_energy.append(0.0)
        fallback_energy.append(0.0)
        if (index + 1) % 1_000_000 == 0:
            print(
                f"Attributed timeline for {index + 1} kernel events...",
                flush=True,
            )

        clipped_start = max(kernel_start, start)
        clipped_end = min(kernel_end, end)
        if clipped_start < clipped_end:
            first_window = (clipped_start - start) // window_ns
            last_window = (clipped_end - 1 - start) // window_ns
            for window_index in range(first_window, last_window + 1):
                window_start = start + window_index * window_ns
                window_end = min(window_start + window_ns, end)
                overlap_start = max(clipped_start, window_start)
                overlap_end = min(clipped_end, window_end)
                previous_end = window_union_end[window_index]
                if overlap_end > previous_end:
                    uncovered_start = max(overlap_start, previous_end)
                    window_active_ns[window_index] += (
                        overlap_end - uncovered_start
                    )
                    window_union_end[window_index] = overlap_end
        return kernel

    next_kernel = read_next_kernel()
    active = {}
    end_heap = []

    for left, right in zip(samples, samples[1:]):
        segment_start = max(start, left[0])
        segment_end = min(end, right[0])
        if segment_start >= segment_end:
            continue

        cursor = segment_start
        while cursor < segment_end:
            while end_heap and end_heap[0][0] <= cursor:
                _, index = heapq.heappop(end_heap)
                active.pop(index, None)

            while next_kernel is not None and next_kernel[1] <= cursor:
                index, _, kernel_end, weight = next_kernel
                if kernel_end > cursor:
                    active[index] = weight
                    heapq.heappush(end_heap, (kernel_end, index))
                next_kernel = read_next_kernel()

            next_start = (
                next_kernel[1]
                if next_kernel is not None and next_kernel[1] < segment_end
                else segment_end
            )
            next_end = end_heap[0][0] if end_heap else segment_end
            boundary = min(segment_end, next_start, next_end)
            if boundary <= cursor:
                raise RuntimeError("Energy attribution sweep did not advance")

            _, dynamic_energy = interval_energy_mj(
                cursor, boundary, left, right, idle_power_mw
            )
            if not active:
                unassigned += dynamic_energy
            else:
                use_pm_weights = all(
                    weight is not None for weight in active.values()
                )
                total_weight = (
                    sum(active.values()) if use_pm_weights else 0.0
                )
                if total_weight > 0.0:
                    for index, weight in active.items():
                        share = dynamic_energy * weight / total_weight
                        estimated_energy[index] += share
                        pm_weighted_energy[index] += share
                    pm_weighted += dynamic_energy
                else:
                    share = dynamic_energy / len(active)
                    for index in active:
                        estimated_energy[index] += share
                        fallback_energy[index] += share
                    fallback += dynamic_energy
                assigned += dynamic_energy
            cursor = boundary

    return {
        "assigned": assigned,
        "unassigned": unassigned,
        "pm_weighted": pm_weighted,
        "fallback": fallback,
        "estimated_energy": estimated_energy,
        "pm_weighted_energy": pm_weighted_energy,
        "fallback_energy": fallback_energy,
        "window_active_ns": window_active_ns,
    }


def pearson(values_x, values_y):
    finite_pairs = [
        (x, y)
        for x, y in zip(values_x, values_y)
        if math.isfinite(x) and math.isfinite(y)
    ]
    values_x = [pair[0] for pair in finite_pairs]
    values_y = [pair[1] for pair in finite_pairs]
    if len(values_x) < 2:
        return math.nan
    mean_x = sum(values_x) / len(values_x)
    mean_y = sum(values_y) / len(values_y)
    centered_x = [value - mean_x for value in values_x]
    centered_y = [value - mean_y for value in values_y]
    denominator = math.sqrt(
        sum(value * value for value in centered_x)
        * sum(value * value for value in centered_y)
    )
    if denominator == 0:
        return math.nan
    return sum(x * y for x, y in zip(centered_x, centered_y)) / denominator


def build_windows(
    samples, window_active_ns, start, end, idle_power_mw, window_ns
):
    windows = []
    window_start = start
    index = 0
    while window_start < end:
        window_end = min(window_start + window_ns, end)
        duration_ns = window_end - window_start
        active_ns = window_active_ns[index]
        device_energy, dynamic_energy = integrate_range(
            samples, window_start, window_end, idle_power_mw
        )
        duration_seconds = duration_ns / NS_PER_SECOND
        windows.append(
            {
                "window": index,
                "start_ns": window_start,
                "end_ns": window_end,
                "duration_ms": duration_ns / 1_000_000,
                "kernel_active_ms": active_ns / 1_000_000,
                "kernel_active_pct": 100.0 * active_ns / duration_ns,
                "device_energy_mj": device_energy,
                "dynamic_energy_mj": dynamic_energy,
                "avg_device_power_mw": device_energy / duration_seconds,
                "avg_dynamic_power_mw": dynamic_energy / duration_seconds,
            }
        )
        index += 1
        window_start = window_end
    return windows


def write_csv(path, rows, fieldnames):
    with path.open("w", newline="", encoding="utf-8") as destination:
        writer = csv.DictWriter(destination, fieldnames=fieldnames, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(rows)


def write_kernel_energy_csv(
    source_path,
    output_path,
    pm_by_event_id,
    estimated_energy,
    pm_weighted_energy,
    fallback_energy,
):
    fieldnames = [
        "event_id", "pid", "device_id", "context_id", "stream_id",
        "correlation_id", "start_ns", "end_ns", "duration_ns",
        "kernel_name", "estimated_dynamic_energy_mj",
        "pm_coverage_pct", "pm_energy_weight", "pm_weighted_energy_mj",
        "equal_share_fallback_energy_mj",
    ]
    valid_index = 0
    with source_path.open(newline="", encoding="utf-8") as source:
        reader = csv.DictReader(source)
        with output_path.open("w", newline="", encoding="utf-8") as destination:
            writer = csv.DictWriter(
                destination, fieldnames=fieldnames, extrasaction="ignore"
            )
            writer.writeheader()
            for row in reader:
                if parse_kernel_row(row) is None:
                    continue
                pm_values = pm_by_event_id.get(row.get("event_id"))
                row["estimated_dynamic_energy_mj"] = (
                    estimated_energy[valid_index]
                    if valid_index < len(estimated_energy)
                    else 0.0
                )
                row["pm_coverage_pct"] = (
                    pm_values[0] if pm_values is not None else ""
                )
                row["pm_energy_weight"] = (
                    pm_values[1]
                    if pm_values is not None and pm_values[1] is not None
                    else ""
                )
                row["pm_weighted_energy_mj"] = (
                    pm_weighted_energy[valid_index]
                    if valid_index < len(pm_weighted_energy)
                    else 0.0
                )
                row["equal_share_fallback_energy_mj"] = (
                    fallback_energy[valid_index]
                    if valid_index < len(fallback_energy)
                    else 0.0
                )
                writer.writerow(row)
                valid_index += 1
                if valid_index % 1_000_000 == 0:
                    print(
                        f"Wrote energy for {valid_index} kernel events...",
                        flush=True,
                    )


def create_plots(output_dir, windows):
    try:
        import matplotlib.pyplot as plt
    except ImportError as error:
        raise RuntimeError(
            "--plot requires matplotlib; install it with: python3 -m pip install matplotlib"
        ) from error

    elapsed_ms = [
        (row["start_ns"] - windows[0]["start_ns"]) / 1_000_000
        for row in windows
    ]
    energy = [row["dynamic_energy_mj"] for row in windows]
    utilization = [row["kernel_active_pct"] for row in windows]

    figure, axis_energy = plt.subplots(figsize=(10, 5))
    axis_utilization = axis_energy.twinx()
    axis_energy.plot(elapsed_ms, energy, color="tab:red", marker="o", label="Energy")
    axis_utilization.plot(
        elapsed_ms,
        utilization,
        color="tab:blue",
        marker=".",
        label="Kernel active time",
    )
    axis_energy.set_xlabel("Window start (ms)")
    axis_energy.set_ylabel("Energy per window (mJ)", color="tab:red")
    axis_utilization.set_ylabel("Kernel active time (%)", color="tab:blue")
    axis_energy.set_title("GPU energy and kernel activity over time")
    figure.tight_layout()
    figure.savefig(output_dir / "energy_timeline.png", dpi=160)
    plt.close(figure)

    figure, axis = plt.subplots(figsize=(6, 5))
    axis.scatter(utilization, energy, alpha=0.75)
    axis.set_xlabel("Kernel active time (%)")
    axis.set_ylabel("Energy per window (mJ)")
    axis.set_title("Kernel activity–energy correlation")
    axis.grid(alpha=0.25)
    figure.tight_layout()
    figure.savefig(output_dir / "utilization_energy_correlation.png", dpi=160)
    plt.close(figure)

def main():
    args = parse_args()
    if args.idle_power_mw < 0:
        raise ValueError("--idle-power-mw cannot be negative")
    if not 0.0 <= args.pm_min_coverage_pct <= 100.0:
        raise ValueError("--pm-min-coverage-pct must be between 0 and 100")
    if args.window_ms <= 0:
        raise ValueError("--window-ms must be greater than zero")
    window_ns = int(args.window_ms * 1_000_000)
    if window_ns < 1:
        raise ValueError("--window-ms must be at least one nanosecond")

    samples = load_telemetry(args.telemetry)
    pm_by_event_id = {}
    if args.pm_kernel_metrics:
        pm_by_event_id = load_pm_kernel_metrics(
            args.pm_kernel_metrics,
            args.pm_weight_metric,
            args.pm_min_coverage_pct,
        )
    print("Scanning kernel activity metadata...", flush=True)
    kernel_metadata = scan_kernel_metadata(args.kernels, pm_by_event_id)
    kernel_count = kernel_metadata["count"]
    print(f"Validated {kernel_count} kernel events.", flush=True)
    pm_matched_kernels = kernel_metadata["pm_matched"]
    pm_eligible_kernels = kernel_metadata["pm_eligible"]
    if kernel_count:
        analysis_start = max(samples[0][0], kernel_metadata["first_start"])
        kernel_span_ns = max(
            0, kernel_metadata["last_end"] - analysis_start
        )
        full_window_end = analysis_start + (
            (kernel_span_ns + window_ns - 1) // window_ns
        ) * window_ns
        analysis_end = min(samples[-1][0], full_window_end)
        if analysis_end < full_window_end:
            print(
                "WARNING: Telemetry does not cover the complete final window; "
                "capture a new run with additional tail sampling."
            )
    else:
        print(
            "WARNING: No valid kernel intervals were found; "
            "analyzing the complete NVML timeline with 0% kernel activity."
        )
        analysis_start = samples[0][0]
        analysis_end = samples[-1][0]
    if analysis_start >= analysis_end:
        raise ValueError("Telemetry and kernel timelines do not overlap")

    device_energy, dynamic_energy = integrate_range(
        samples, analysis_start, analysis_end, args.idle_power_mw
    )
    if kernel_count:
        print("Attributing energy with a chronological sweep...", flush=True)
        attribution = attribute_energy_streaming(
            samples,
            args.kernels,
            pm_by_event_id,
            analysis_start,
            analysis_end,
            args.idle_power_mw,
            window_ns,
        )
    else:
        window_count = (
            analysis_end - analysis_start + window_ns - 1
        ) // window_ns
        attribution = {
            "assigned": 0.0,
            "unassigned": dynamic_energy,
            "pm_weighted": 0.0,
            "fallback": 0.0,
            "estimated_energy": array("d"),
            "pm_weighted_energy": array("d"),
            "fallback_energy": array("d"),
            "window_active_ns": array("d", [0.0]) * window_count,
        }
    windows = build_windows(
        samples,
        attribution["window_active_ns"],
        analysis_start,
        analysis_end,
        args.idle_power_mw,
        window_ns,
    )
    utilization = [row["kernel_active_pct"] for row in windows]
    dynamic_window_energy = [row["dynamic_energy_mj"] for row in windows]
    dynamic_power = [row["avg_dynamic_power_mw"] for row in windows]
    energy_correlation = pearson(utilization, dynamic_window_energy)
    power_correlation = pearson(utilization, dynamic_power)
    assigned = attribution["assigned"]
    unassigned = attribution["unassigned"]
    pm_weighted_energy = attribution["pm_weighted"]
    fallback_energy = attribution["fallback"]
    conservation_error = dynamic_energy - assigned - unassigned

    args.output_dir.mkdir(parents=True, exist_ok=True)
    window_fields = list(windows[0].keys())
    print("Writing per-kernel energy results...", flush=True)
    write_kernel_energy_csv(
        args.kernels,
        args.output_dir / "kernel_energy.csv",
        pm_by_event_id,
        attribution["estimated_energy"],
        attribution["pm_weighted_energy"],
        attribution["fallback_energy"],
    )
    write_csv(args.output_dir / "energy_windows.csv", windows, window_fields)

    summary = [
        {"metric": "analysis_start_ns", "value": analysis_start},
        {"metric": "analysis_end_ns", "value": analysis_end},
        {"metric": "idle_power_mw", "value": args.idle_power_mw},
        {"metric": "device_energy_mj", "value": device_energy},
        {"metric": "dynamic_energy_mj", "value": dynamic_energy},
        {"metric": "assigned_dynamic_energy_mj", "value": assigned},
        {"metric": "unassigned_dynamic_energy_mj", "value": unassigned},
        {"metric": "conservation_error_mj", "value": conservation_error},
        {"metric": "utilization_dynamic_energy_pearson_r", "value": energy_correlation},
        {"metric": "utilization_dynamic_power_pearson_r", "value": power_correlation},
        {
            "metric": "attribution_method",
            "value": (
                "hybrid_pm_weighted_with_equal_share_fallback"
                if args.pm_kernel_metrics
                else "equal_share_concurrent_kernels"
            ),
        },
        {"metric": "pm_weight_metric", "value": args.pm_weight_metric if args.pm_kernel_metrics else ""},
        {"metric": "pm_min_coverage_pct", "value": args.pm_min_coverage_pct if args.pm_kernel_metrics else ""},
        {"metric": "pm_matched_kernels", "value": pm_matched_kernels},
        {"metric": "pm_eligible_kernels", "value": pm_eligible_kernels},
        {"metric": "pm_weighted_energy_mj", "value": pm_weighted_energy},
        {"metric": "equal_share_fallback_energy_mj", "value": fallback_energy},
    ]
    write_csv(args.output_dir / "energy_summary.csv", summary, ["metric", "value"])
    if args.plot:
        create_plots(args.output_dir, windows)

    print("=== Kernel energy association ===")
    print(f"Kernels: {kernel_count}")
    print(f"Windows: {len(windows)}")
    print(f"Dynamic energy: {dynamic_energy:.6f} mJ")
    print(f"Assigned to kernels: {assigned:.6f} mJ")
    print(f"Unassigned: {unassigned:.6f} mJ")
    if args.pm_kernel_metrics:
        print(
            "PM-weighted kernels: "
            f"{pm_eligible_kernels} / {kernel_count} "
            f"(>= {args.pm_min_coverage_pct:.1f}% coverage)"
        )
        print(f"PM-weighted energy: {pm_weighted_energy:.6f} mJ")
        print(f"Equal-share fallback energy: {fallback_energy:.6f} mJ")
    print(f"Utilization-energy Pearson r: {energy_correlation:.6f}")
